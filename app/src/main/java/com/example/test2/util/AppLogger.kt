package com.example.test2.util

import android.util.Log
import com.example.test2.BuildConfig

/**
 * Centralized debug-aware logger ensuring all debug/error logs respect [BuildConfig.DEBUG]
 * and exceptions are never silently swallowed without diagnostic visibility in debug builds.
 */
object AppLogger {
    fun d(tag: String, message: String) {
        if (BuildConfig.DEBUG) {
            Log.d(tag, message)
        }
    }

    fun w(tag: String, message: String, throwable: Throwable? = null) {
        if (BuildConfig.DEBUG) {
            if (throwable != null) {
                Log.w(tag, message, throwable)
            } else {
                Log.w(tag, message)
            }
        }
    }

    fun e(tag: String, message: String, throwable: Throwable? = null) {
        if (BuildConfig.DEBUG) {
            if (throwable != null) {
                Log.e(tag, message, throwable)
            } else {
                Log.e(tag, message)
            }
        }
    }
}
